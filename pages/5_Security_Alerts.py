"""
SentinelNet: Security Alert Management Page.
Facilitates incident triage, severity-based filtering, keyword search,
alert acknowledgment, and CSV export backed by SQLite persistence.
"""

import sys
from pathlib import Path
import streamlit as st
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from src.alert_manager import AlertManager
from src.database import DatabaseManager
from src.utils import get_security_theme_css

st.set_page_config(page_title="Security Alerts | SentinelNet", page_icon="🚨", layout="wide")
st.markdown(get_security_theme_css(), unsafe_allow_html=True)

st.title("🚨 Security Incident & Alert Management")
st.markdown(
    "Manage, search, and acknowledge cybersecurity alerts generated by SentinelNet's "
    "**Deterministic Rule Engine**, **Isolation Forest Anomaly Detector**, and **Hybrid Correlation Engine**."
)

db_mgr = DatabaseManager()
alert_mgr = AlertManager(db_manager=db_mgr)

# High-Level Metrics
stats = alert_mgr.get_summary_statistics()

m1, m2, m3, m4, m5 = st.columns(5)
m1.metric("Total Recorded", stats["total_alerts"])
m2.metric("Unacknowledged", stats["unacknowledged"], delta_color="inverse")
m3.metric("Critical", stats["critical"])
m4.metric("High", stats["high"])
m5.metric("Medium / Low", stats["medium"] + stats["low"])

st.markdown("---")

# Filter & Search Controls
col_f1, col_f2, col_f3, col_f4 = st.columns([1.5, 1.5, 2.5, 1.5])

with col_f1:
    severity_filter = st.selectbox(
        "Filter Severity",
        options=["ALL", "Critical", "High", "Medium", "Low"],
        index=0,
    )

with col_f2:
    status_filter = st.selectbox(
        "Triage Status",
        options=["ALL", "Unacknowledged", "Acknowledged"],
        index=0,
    )
    ack_bool = None
    if status_filter == "Unacknowledged":
        ack_bool = False
    elif status_filter == "Acknowledged":
        ack_bool = True

with col_f3:
    search_query = st.text_input("🔍 Search Alerts", placeholder="Search by IP, alert type, or keywords...")

with col_f4:
    st.markdown("<br>", unsafe_allow_html=True)
    if st.button("🔄 Refresh Data", use_container_width=True):
        st.rerun()

# Retrieve matching alerts from SQLite
alerts_df = alert_mgr.get_alerts_dataframe(
    severity=severity_filter if severity_filter != "ALL" else None,
    acknowledged=ack_bool,
    search_query=search_query if search_query.strip() else None,
    limit=500,
)

st.markdown("###")

if alerts_df.empty:
    st.info("No security alerts matching the current filter criteria.")
else:
    st.caption(f"Displaying {len(alerts_df)} matching alerts (ordered newest first)")

    # Render each alert card
    for _, row in alerts_df.iterrows():
        alert_id = int(row["id"])
        severity = row.get("severity", "Medium")
        alert_type = row.get("alert_type", "Security Event")
        detection_method = row.get("detection_method", "Rule-Based")
        src_ip = row.get("src_ip", "N/A")
        dst_ip = row.get("dst_ip", "N/A")
        ts = row.get("timestamp", "N/A")
        explanation = row.get("explanation", "")
        recommended = row.get("recommended_action", "Investigate traffic.")
        is_ack = bool(row.get("acknowledged", False))
        score = row.get("anomaly_score")

        badge_class = f"badge-{severity.lower()}"

        with st.container():
            col_card_left, col_card_right = st.columns([4, 1])

            with col_card_left:
                st.markdown(
                    f"""
                    <div style="background:#111827; border: 1px solid #1f2937; border-radius: 8px; padding: 14px; margin-bottom: 12px;">
                        <div style="display:flex; justify-content:space-between; align-items:center; margin-bottom: 8px;">
                            <div>
                                <span class="{badge_class}">{severity.upper()}</span>
                                <strong style="font-size: 1.1rem; margin-left: 8px; color: #f3f4f6;">{alert_type}</strong>
                                <span style="color: #9ca3af; font-size: 0.85rem; margin-left: 10px;">[{detection_method}]</span>
                            </div>
                            <span style="color: #6b7280; font-size: 0.82rem;">{ts}</span>
                        </div>
                        <div style="color: #d1d5db; font-size: 0.9rem; margin-bottom: 6px;">
                            <strong>Attacker / Source:</strong> <code>{src_ip}</code> &nbsp; ➜ &nbsp; 
                            <strong>Target / Dest:</strong> <code>{dst_ip}</code>
                            {" &nbsp;|&nbsp; <strong>Score:</strong> <code>" + str(score) + "</code>" if score is not None else ""}
                        </div>
                        <div style="color: #9ca3af; font-size: 0.87rem; margin-bottom: 6px;">
                            <strong>Details:</strong> {explanation}
                        </div>
                        <div style="color: #60a5fa; font-size: 0.85rem;">
                            <strong>Recommended Defense:</strong> {recommended}
                        </div>
                    </div>
                    """,
                    unsafe_allow_html=True,
                )

            with col_card_right:
                if not is_ack:
                    if st.button("✔️ Acknowledge", key=f"ack_{alert_id}", use_container_width=True):
                        alert_mgr.acknowledge(alert_id)
                        st.toast(f"Alert #{alert_id} marked as acknowledged.")
                        st.rerun()
                else:
                    st.markdown("<span style='color:#10b981; font-weight:600;'>✔️ Acknowledged</span>", unsafe_allow_html=True)

st.markdown("---")

# Export and Reset Actions
col_exp, col_reset = st.columns([3, 1])

with col_exp:
    st.subheader("📥 Export Alerts")
    csv_bytes = alerts_df.to_csv(index=False).encode("utf-8")
    st.download_button(
        label="Download Alerts as CSV",
        data=csv_bytes,
        file_name="sentinelnet_security_alerts.csv",
        mime="text/csv",
    )

with col_reset:
    st.subheader("🗑️ Reset Database")
    if st.button("Reset Demo Data", type="secondary", help="Clears stored alerts and sessions from SQLite."):
        db_mgr.reset_demo_data()
        st.success("Demo records cleared successfully.")
        st.rerun()
